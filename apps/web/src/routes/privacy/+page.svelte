<div class="page-body legal">
  <p class="lede">
    God&rsquo;s Word is a reading application. It does not require an account, and it does not
    collect, transmit, or sell personal information.
  </p>

  <h2>What we store</h2>
  <p>
    Your preferences &mdash; text size, appearance, ministry mode, and voice settings &mdash; are saved
    in your browser&rsquo;s local storage on your own device. They never leave it, and clearing your
    browser data removes them.
  </p>

  <h2>What we don&rsquo;t collect</h2>
  <p>
    We do not use advertising trackers or third-party analytics. We do not build a profile of you,
    and we do not ask for your name, email address, or location.
  </p>

  <h2>Offline use</h2>
  <p>
    The application caches readings and prayers on your device so it works without a connection.
    This cache is local to your browser and is cleared when you clear site data.
  </p>

  <h2>Hosting</h2>
  <p>
    The site is served as static files from a content delivery network. As with any website, the
    hosting provider may process standard request information (such as IP address) transiently in
    order to deliver pages and protect the service. We do not receive or retain those logs.
  </p>

  <h2>Audio</h2>
  <p>
    Where recordings are available they are streamed from our media storage. Playing audio makes a
    request for that file; nothing further is recorded.
  </p>

  <h2>Children</h2>
  <p>
    The application is suitable for all ages and does not knowingly collect information from anyone.
  </p>

  <h2>Changes</h2>
  <p>
    If this policy changes, the revised date above will be updated. Material changes will be noted
    in the application.
  </p>

